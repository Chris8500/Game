"""Bake collision data from PNG alpha; requires Pillow only when artwork changes.

Does not modify the artwork. Run from any directory with Python and Node available.
"""
import hashlib
import json
import math
from pathlib import Path
import subprocess
from PIL import Image

root = Path(__file__).resolve().parent.parent
query = """const E=require('./src/engine.js');console.log(JSON.stringify({
stand:E.enemyPose({x:0,facing:-1}),
walk:Array.from({length:8},(_,phase)=>E.enemyPose({x:0,facing:-1,moving:true,phase}))}));"""
poses = json.loads(subprocess.check_output(['node', '-e', query], cwd=root, text=True))

def inside(x, y, polygon):
    if not polygon:
        return True
    result = False
    for (ax, ay), (bx, by) in zip(polygon, polygon[1:] + polygon[:1]):
        if (ay > y) != (by > y) and x < (bx - ax) * (y - ay) / (by - ay) + ax:
            result = not result
    return result

def bake(image, pose, step):
    alpha = image.getchannel('A')
    sx, sy, width, height = pose['rect']
    rows = []
    for row in range(math.ceil(height / step)):
        spans, start = [], None
        for col in range(math.ceil(width / step)):
            x = min(sx + col * step + step // 2, sx + width - 1)
            y = min(sy + row * step + step // 2, sy + height - 1)
            solid = alpha.getpixel((x, y)) >= 64 and inside(x, y, pose.get('clip'))
            if solid and start is None:
                start = col
            if not solid and start is not None:
                spans.extend([start, col])
                start = None
        if start is not None:
            spans.extend([start, math.ceil(width / step)])
        rows.append(spans)
    return {'step': step, 'rows': rows}

standing = Image.open(root / 'assets/enemy.png').convert('RGBA')
walking = Image.open(root / 'assets/enemy-walk.png').convert('RGBA')
data = {
    'sources': {name: hashlib.sha256((root / 'assets' / name).read_bytes()).hexdigest()
                for name in ['enemy.png', 'enemy-walk.png']},
    'stand': bake(standing, poses['stand'], 4),
    'walk': [bake(walking, pose, 2) for pose in poses['walk']],
}
encoded = json.dumps(data, separators=(',', ':'))
output = '// Generated by scripts/prepare-hit-masks.py from alpha >= 64. Do not edit.\n'
output += "(function(root){const masks=" + encoded + ";\n"
output += "if(typeof module!=='undefined'&&module.exports)module.exports=masks;else root.NoirEnemyHitMasks=masks;\n})(typeof globalThis!=='undefined'?globalThis:this);\n"
(root / 'src/enemy-hit-masks.js').write_text(output, encoding='utf-8')
print('Baked nine enemy silhouettes (< 1.1 game pixels per cell).')
